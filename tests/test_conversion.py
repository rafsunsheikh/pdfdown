"""End-to-end checks on real documents. Each test pins a problem found while building pdfdown.

The office PDFs are generated by scripts/make_office_samples.py and live in git.
The arXiv papers and the Nature article are not redistributable, so their tests
are skipped when the files are missing. Point PDFDOWN_NATURE_PDF at the Nature article to run its test.
"""

import os
import re
from pathlib import Path

import pytest

from pdfdown.cleanup import clean
from pdfdown.document import from_docling
from pdfdown.engine import EngineOptions, cache_path, convert
from pdfdown.export import write
from pdfdown.quality import scan

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / "corpus"
NATURE = Path(os.environ.get("PDFDOWN_NATURE_PDF", "s41586-025-09922-y.pdf"))  # a Nature article; not redistributable


def need(path: Path) -> Path:
    if not path.is_file():
        pytest.skip(f"{path.name} not available")
    return path


@pytest.fixture(scope="module")
def converted(tmp_path_factory):
    out = tmp_path_factory.mktemp("out")
    cache: dict[str, tuple] = {}

    def get(path: Path):
        if path.name not in cache:
            doc = clean(from_docling(convert(path), path))
            md = write(doc, out)
            cache[path.name] = (doc, md, md.read_text(encoding="utf-8"))
        return cache[path.name]

    return get


def test_engine_result_is_cached():
    pdf = need(CORPUS / "office-report.pdf")
    convert(pdf)
    assert cache_path(pdf, EngineOptions()).is_file()


def test_office_report(converted):
    doc, md, text = converted(need(CORPUS / "office-report.pdf"))
    assert text.startswith("# Annual Operations Review 2025")
    assert "Northwind Analytics | Internal report" not in text  # running header removed
    assert "- Revenue rose 18% year on year" in text
    assert "| Region" in text or "<table" in text  # the merged-header table survives
    assert (md.parent / "figures").is_dir() and any((md.parent / "figures").iterdir())
    assert scan(md) == [] or all(f.kind == "duplicated lines" for f in scan(md))  # the sample repeats filler text on purpose


def test_slides(converted):
    _, md, text = converted(need(CORPUS / "office-slides.pdf"))
    assert "Q4 Business Update" in text and "- Churn down to 4.3%" in text
    assert scan(md) == []


def test_nature_article(converted):
    doc, md, text = converted(need(NATURE))
    assert text.startswith("# Artificial intelligence tools expand scientists’ impact but contract science’s focus")
    assert "Qianyue Hao<sup>1</sup>, Fengli Xu<sup>1</sup>" in text  # superscript affiliations
    assert "prizes<sup>2–9</sup>" in text and "education<sup>12,13</sup>" in text  # superscript citations
    assert "N(t<sub>0</sub>)" in text  # subscripts, barely lowered in this font
    assert "## Methods" in text and "## Article" not in text  # running header removed, even merged into a heading
    assert "Time Time" not in text  # axis labels beside a figure dropped
    assert "on the basis of 41,298,433 papers" in text  # paragraph stitched across a column break
    assert "decades" in text and "dec ades" not in text  # line-end hyphen joined
    assert (md.parent / "figures/figure-2.png").is_file()
    numbers = [b.extra.get("number") for b in doc.of_kind("figure")]
    assert numbers == ["1", "2", "3", "4"] + [f"ED{n}" for n in range(1, 11)]  # captions Docling called text or headings
    assert "Extended Data Fig. 2 | Procedure of accuracy evaluation via expert evaluation. We randomly" in text
    assert scan(md) == [] or all(f.kind == "paragraphs ending mid-sentence" for f in scan(md))


def test_bert_two_columns_and_tables(converted):
    doc, md, text = converted(need(CORPUS / "bert-1810.04805.pdf"))
    assert text.startswith("# BERT: Pre-training of Deep Bidirectional Transformers for Language Understanding")
    assert "BERT<sub>BASE</sub>" in text
    assert "jointly" in text and "j ointly" not in text  # "j" overhangs the space before it
    assert text.count("Table 2: SQuAD 1.1 results") == 1  # caption once, attached by Docling's link
    assert "<caption>" not in text
    assert not [f for f in scan(md) if f.kind in ("letters split apart", "captions written twice", "images that do not exist")]


def test_attention_panels(converted):
    doc, md, text = converted(need(CORPUS / "attention-1706.03762.pdf"))
    figures = sorted(p.name for p in (md.parent / "figures").iterdir())
    assert "figure-2a.png" in figures and "figure-2b.png" in figures  # two images, one caption: nothing overwritten
    assert text.count("*Figure 2: (left) Scaled Dot-Product Attention") == 1


EXAMPLES = ROOT / "examples"


def test_llama_first_page_reading_order(converted):
    # The layout step read the right column before the abstract; the author list came out as a heading.
    _, _, text = converted(need(EXAMPLES / "llama/llama.pdf"))
    assert text.index("## Abstract") < text.index("## 1 Introduction") < text.index("The focus of this work")
    assert "\nHugo Touvron<sup>∗</sup>" in text and "## Hugo" not in text
    assert "reach a certain level of performance, a smaller one trained longer" in text  # joined across the columns


def test_tex_accents_and_two_columns(converted):
    _, md, text = converted(need(EXAMPLES / "imaginary-magnetic-fields/imaginary-magnetic-fields.pdf"))
    assert "Juzeliūnas" in text and "¯u" not in text
    assert not [f for f in scan(md) if f.kind in ("letters split apart", "images that do not exist")]


def test_accents_stay_on_their_letter(converted):
    # Adam: the bar of θ̄ sits under a line with a tall ∑, and must not join that line or a word near it.
    _, _, text = converted(need(CORPUS / "adam-1412.6980.pdf"))
    assert "SGD, where θ̄<sub>t</sub>" in text and "algorithms 1 and 2: θ̄<sub>t</sub> ←" in text
    assert "an exponential moving average over the parameters can be used" in text
